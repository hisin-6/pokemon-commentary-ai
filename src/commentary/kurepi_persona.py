def battle_result_line(battle_result: str) -> str:
    """battle_end時、締めの実況で勝敗に触れさせるための追加ルール行。"""
    return (
        f"- この試合の勝敗は「自分の{battle_result}」で確定している。"
        "締めの実況で必ず勝敗に触れること（勝ちなら喜び・負けなら悔しさ＋前向きな一言）")


def battle_surrendered_line(battle_result: str | None) -> str:
    """battle_end時、降参による決着だと明示するための追加ルール行。

    「降参が選ばれました」で終わった試合はポケモンが倒れて全滅したわけではない。
    実況が気絶・全滅を捏造しないよう明示する（実機2026-08-14_20-46-44で
    「ブリジュラスが落ちた、これで自分の手持ちが全滅です」という捏造を確認）。
    battle_result_line()と同じくキャラ名・口調に依存しないため両ペルソナで共用する。
    """
    if battle_result == "勝ち":
        who = "相手が降参を選んだ"
    elif battle_result == "負け":
        who = "自分が降参を選んだ"
    else:
        who = "どちらの降参かは不明・断定しない"
    return (
        f"- この試合は降参（ギブアップ）によって終了した（{who}）。ポケモンが倒れて"
        "決着したわけではないので、最後のポケモンが倒れた・全滅したという描写を"
        "絶対にしないこと")
