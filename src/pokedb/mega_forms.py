"""メガシンカによるタイプ変化の静的データ（改善ロードマップ「戦況推論強化」続き・2026-08-04）。

`src/pokedb/type_chart.py`と同じ設計思想: ゲーム根幹ルールの静的データであり、
非公式の対戦統計・使用率データとは別物。

ほとんどのメガシンカはタイプが変化しない（能力値・特性のみ変化）ため、
**タイプが変化する種のみ**収録する。無いポケモンは`_compute_type_hint`側で
元のタイプがそのまま使われる（変化なし、で正しい）。

⚠️ 確度の高い代表例（メガリザードンX・メガミュウツーX）のみ最初に収録。
他のメガシンカも段階的に追加できる設計（辞書に追記するだけ）。
"""

from __future__ import annotations

# 進化前の和名 → メガシンカ後のタイプ
_MEGA_TYPE_OVERRIDES: dict[str, list[str]] = {
    "リザードン": ["ほのお", "ドラゴン"],   # メガリザードンX（ほのお/ひこう → ほのお/ドラゴン）
    "ミュウツー": ["エスパー", "かくとう"],  # メガミュウツーX（エスパー → エスパー/かくとう）
}


def get_mega_types(base_name_ja: str) -> list[str] | None:
    """進化前の和名からメガシンカ後のタイプを引く。タイプ変化が無い/未収録の種はNone
    （呼び出し側は元のタイプをそのまま使うこと）。"""
    return _MEGA_TYPE_OVERRIDES.get(base_name_ja)
