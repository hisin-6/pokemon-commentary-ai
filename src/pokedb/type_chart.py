def effectiveness_multiplier(move_type: str, defender_types: list[str]) -> float:
    """攻撃技のタイプが、防御側の（複数の場合ある）タイプに対して持つ効果倍率を返す。

    defender_typesが空/Noneの場合は1.0（不明時は相性なしとして安全側に倒す）。
    """
    if not defender_types:
        return 1.0
    mult = 1.0
    per_type = _CHART.get(move_type, {})
    for d_type in defender_types:
        mult *= per_type.get(d_type, 1.0)
    return mult


def describe_matchup(move_type: str, defender_types: list[str]) -> str:
    """倍率を「バツグン」等の日本語ラベルに変換する。"""
    mult = effectiveness_multiplier(move_type, defender_types)
    for threshold, label in _LABELS:
        if mult >= threshold:
            return label
    return "等倍"  # 到達しないはずのフォールバック
